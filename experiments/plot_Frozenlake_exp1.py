import sys
from pathlib import Path
from matplotlib.ticker import MaxNLocator

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


# -----------------------------
# Paths
# -----------------------------
RESULT_DIR = PROJECT_ROOT / "results" / "Frozenlake_exp1"
RESULT_PATH = RESULT_DIR / "Frozenlake_exp1_results.csv"
DR_RESULT_PATH = RESULT_DIR / "Frozenlake_exp1_domain_randomization.csv"

FIGURE_DIR = PROJECT_ROOT / "figures" / "Frozenlake_exp1"
FIGURE_DIR.mkdir(parents=True, exist_ok=True)


# -----------------------------
# Plot style
# -----------------------------
FIGSIZE = (6.5, 4.2)
LINE_WIDTH = 2.0
SHADE_ALPHA = 0.15
GRID_ALPHA = 0.25

EXPECTED_EPS = np.array([0.10, 0.20, 0.30, 0.35])
EXPECTED_UNCERTAINTY_DISTANCES = {"support_restricted_tv_l1", "none"}
EXPECTED_ROBUST_BACKUP_TYPES = {"exact_support_restricted_l1", "nominal_mixture_bellman"}

METHOD_ORDER = [
    "Maximum-based",
    "Similarity-aware",
    "Uniform",
    "Non-robust DR",
]

PLOT_STYLES = {
    "Maximum-based": {
        "color": "C2",
        "linestyle": "-",
    },
    "Similarity-aware": {
        "color": "C0",
        "linestyle": "-",
    },
    "Uniform": {
        "color": "C1",
        "linestyle": "-",
    },
    "Non-robust DR": {
        "color": "C4",
        "linestyle": "-",
    },
}


def set_clean_yticks_keep_limits(ax, nbins=6):
    """Use clean y-axis ticks without changing the current y-axis limits."""
    ymin, ymax = ax.get_ylim()
    ax.yaxis.set_major_locator(MaxNLocator(nbins=nbins))
    ax.set_ylim(ymin, ymax)


def mean_and_sem(x, axis=0):
    x = np.asarray(x, dtype=float)
    mean = np.mean(x, axis=axis)

    if x.shape[axis] <= 1:
        sem = np.zeros_like(mean)
    else:
        sem = np.std(x, axis=axis, ddof=1) / np.sqrt(x.shape[axis])

    return mean, sem


def main():
    if not RESULT_PATH.exists():
        raise FileNotFoundError(f"Result file not found: {RESULT_PATH}")
    if not DR_RESULT_PATH.exists():
        raise FileNotFoundError(
            "Domain-randomization result file not found: "
            f"{DR_RESULT_PATH}. Run experiments/"
            "Frozenlake_exp1_domain_randomization.py first."
        )

    # The original three methods and domain randomization are generated by
    # separate scripts, but use the same row schema and source realizations.
    df = pd.concat(
        [pd.read_csv(RESULT_PATH), pd.read_csv(DR_RESULT_PATH)],
        ignore_index=True,
        sort=False,
    )

    required_cols = {
        "run_id",
        "iteration",
        "method",
        "normalized_performance",
        "uncertainty_distance",
        "robust_backup_type",
    }

    missing_cols = required_cols - set(df.columns)
    if missing_cols:
        raise ValueError(f"Missing required columns: {missing_cols}")

    uncertainty_types = set(df["uncertainty_distance"].dropna().unique())
    backup_types = set(df["robust_backup_type"].dropna().unique())
    metadata_eps = np.sort(
        df.loc[df["method"] == "source_metadata", "perturb_epsilon"]
        .dropna()
        .unique()
        .astype(float)
    )

    if not uncertainty_types.issubset(EXPECTED_UNCERTAINTY_DISTANCES):
        raise ValueError(f"Unexpected uncertainty distance: {uncertainty_types}")
    if not backup_types.issubset(EXPECTED_ROBUST_BACKUP_TYPES):
        raise ValueError(f"Unexpected robust backup: {backup_types}")
    if not np.allclose(metadata_eps, EXPECTED_EPS):
        raise ValueError(
            f"Unexpected perturb eps: {metadata_eps}; expected {EXPECTED_EPS}."
        )

    perf = df[df["method"].isin(METHOD_ORDER)].copy()
    perf = perf.dropna(subset=["run_id", "iteration", "normalized_performance"])
    perf = perf[perf["iteration"].astype(int) >= 0].copy()

    if perf.empty:
        raise ValueError(
            "No matching performance rows found. Please make sure the two "
            "FrozenLake Exp1 result files contain Maximum-based, "
            "Similarity-aware, Uniform, and Non-robust DR."
        )

    method_tables = {}
    for method_name in METHOD_ORDER:
        method_df = perf[perf["method"] == method_name]
        if method_df.empty:
            raise ValueError(f"Missing method in results: {method_name}")

        method_tables[method_name] = (
            method_df
            .pivot(index="run_id", columns="iteration", values="normalized_performance")
            .sort_index(axis=0)
            .sort_index(axis=1)
        )

    common_iterations = None
    for method_name in METHOD_ORDER:
        method_iterations = method_tables[method_name].columns.to_numpy()
        if common_iterations is None:
            common_iterations = method_iterations
        else:
            common_iterations = np.intersect1d(
                common_iterations,
                method_iterations,
            )

    if common_iterations is None or len(common_iterations) == 0:
        raise ValueError("The four methods do not share any evaluation iterations.")

    curve_stats = {}
    for method_name in METHOD_ORDER:
        curves = method_tables[method_name][common_iterations].to_numpy()
        mean_curve, sem_curve = mean_and_sem(curves, axis=0)
        curve_stats[method_name] = {
            "mean": 100.0 * mean_curve,
            "sem": 100.0 * sem_curve,
        }

    # -----------------------------
    # Plot: normalized target performance mean ± SEM
    # -----------------------------
    fig, ax = plt.subplots(figsize=FIGSIZE)

    for method_name in METHOD_ORDER:
        style = PLOT_STYLES[method_name]
        mean_curve = curve_stats[method_name]["mean"]
        sem_curve = curve_stats[method_name]["sem"]

        ax.plot(
            common_iterations,
            mean_curve,
            color=style["color"],
            linestyle=style["linestyle"],
            linewidth=LINE_WIDTH,
            label=("Domain randomization" if method_name == "Non-robust DR" else method_name),
        )

        ax.fill_between(
            common_iterations,
            mean_curve - sem_curve,
            mean_curve + sem_curve,
            color=style["color"],
            alpha=SHADE_ALPHA,
            linewidth=0.0,
        )

    ax.set_xlabel(r"$t$")
    ax.set_ylabel(r"$\nu(t)$ (%)")

    ax.set_axisbelow(True)
    ax.grid(True, which="major", axis="both", alpha=GRID_ALPHA)
    ax.legend(loc="lower right")

    ymin, ymax = ax.get_ylim()
    yrange = ymax - ymin
    ax.set_ylim(
        max(0.0, ymin - 0.02 * yrange),
        ymax + 0.05 * yrange,
    )
    set_clean_yticks_keep_limits(ax, nbins=6)

    fig.tight_layout()

    pdf_path = FIGURE_DIR / "Frozenlake_exp1.pdf"
    png_path = FIGURE_DIR / "Frozenlake_exp1.png"
    fig.savefig(pdf_path)
    fig.savefig(png_path, dpi=300)
    plt.close(fig)

    print("FrozenLake Exp1 plot regenerated from saved results.")
    print(f"Loaded results from: {RESULT_PATH}")
    print(f"Loaded domain-randomization results from: {DR_RESULT_PATH}")
    print(f"PDF saved to: {pdf_path}")
    print(f"PNG saved to: {png_path}")

    print("\nSummary:")
    final_t = int(common_iterations[-1])
    for method_name in METHOD_ORDER:
        values = method_tables[method_name][final_t].to_numpy(dtype=float)
        mean_y, sem_y = mean_and_sem(values, axis=0)
        print(
            f"{method_name}: "
            f"t={final_t}, "
            f"mean={100.0 * mean_y:.2f}, "
            f"sem={100.0 * sem_y:.2f}, "
            f"n={len(values)}"
        )


if __name__ == "__main__":
    main()
